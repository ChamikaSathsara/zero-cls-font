#!/usr/bin/env node
import { Command } from 'commander';
import * as fs from 'fs';
import * as path from 'path';
import { generateZeroClsCss } from './calculator';
import { SystemFallbackName } from './metrics';

const program = new Command();

program
  .name('zero-cls-font')
  .description('Generate zero-CLS @font-face fallback CSS from any TTF/OTF/WOFF2 file')
  .version('1.0.0')
  .requiredOption('-f, --font <path>', 'Path to the .woff2, .ttf, or .otf font file')
  .option('-b, --fallback <name>', 'System fallback font (Arial, Times New Roman, Courier New, Roboto)', 'Arial')
  .option('-u, --url <url>', 'Public URL path for the primary @font-face rule')
  .option('-o, --out <path>', 'Output CSS file path (prints to stdout if omitted)')
  .action((opts) => {
    try {
      const resolvedPath = path.resolve(process.cwd(), opts.font);
      const result = generateZeroClsCss({
        fontPath: resolvedPath,
        fallbackFont: opts.fallback as SystemFallbackName,
        customFontUrl: opts.url,
      });

      if (opts.out) {
        const outPath = path.resolve(process.cwd(), opts.out);
        fs.writeFileSync(outPath, result.css, 'utf-8');
        console.log(`✅ Zero-CLS fallback CSS written to ${outPath}`);
      } else {
        console.log('\n/* --- Generated by zero-cls-font --- */\n');
        console.log(result.css);
      }
    } catch (error: any) {
      console.error(`❌ Error calculating font metrics: ${error.message}`);
      process.exit(1);
    }
  });

program.parse();
